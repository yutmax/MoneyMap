/*
 * Service worker, который ничего не кеширует.
 *
 * Он здесь не ради офлайна, а ради установки. Chrome на Android заводит
 * настоящее приложение (WebAPK, своя иконка, запуск без адресной строки)
 * только для сайта, прошедшего проверку устанавливаемости, а в неё входит
 * «есть воркер с обработчиком fetch». Без него «добавить на главный экран»
 * создаёт обычный ярлык, который открывается внутри браузера — со строкой
 * адреса и кнопками.
 *
 * Обработчик fetch намеренно пустой: не вызывая respondWith, он оставляет
 * запрос браузеру. Кеш приложения, в котором лежит учёт денег, — отдельное
 * решение с отдельной ценой: устаревший экран с чужими цифрами хуже, чем
 * честное «нет сети». Появится потребность в офлайне — появится и стратегия.
 */

self.addEventListener('install', () => {
  // Новая версия вытесняет старую сразу, а не после закрытия всех вкладок:
  // ждать нечего, состояния воркер не хранит.
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', () => {});
