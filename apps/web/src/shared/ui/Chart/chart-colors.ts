/**
 * Палитра для графиков.
 *
 * Шаги для светлой и тёмной темы подобраны отдельно, а не выведены один из
 * другого осветлением: автоматический переворот даёт на тёмном фоне либо
 * блёклые, либо кислотные цвета. Обе проверены валидатором на наших
 * поверхностях (#f6f7f4 и #242529) — на полосу светлоты, насыщенность,
 * различимость соседних пар при дальтонизме и контраст с фоном.
 *
 * Порядок закреплён: цвет принадлежит сущности, а не месту в списке.
 * Фильтр, убравший одну валюту, не перекрашивает остальные. Девятого цвета
 * нет намеренно — хвост сворачивается в «прочее», а не получает
 * сгенерированный оттенок, неотличимый от соседнего.
 */
export const CHART_SERIES = [
  { light: '#2a78d6', dark: '#3987e5' },
  { light: '#eb6834', dark: '#d95926' },
  { light: '#1baf7a', dark: '#199e70' },
  { light: '#eda100', dark: '#c98500' },
  { light: '#e87ba4', dark: '#d55181' },
  { light: '#4a3aa7', dark: '#9085e9' },
] as const;

/**
 * CSS-переменная серии: тема переключается каскадом, а не пересборкой
 * компонента — в разметку уезжает var(), а значения живут в стилях.
 */
export function seriesColor(index: number): string {
  return `var(--chart-series-${(index % CHART_SERIES.length) + 1})`;
}
